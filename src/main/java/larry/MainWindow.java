package larry;

import javafx.fxml.FXML;
import javafx.geometry.Insets;
import javafx.geometry.Pos;
import javafx.scene.control.Button;
import javafx.scene.control.Label;
import javafx.scene.control.ScrollPane;
import javafx.scene.control.TextField;
import javafx.scene.layout.HBox;
import javafx.scene.layout.VBox;

/**
 * Controller for the main GUI.
 */
public class MainWindow {

    @FXML
    private VBox dialogContainer;

    @FXML
    private ScrollPane scrollPane;

    @FXML
    private TextField userInput;

    @FXML
    private Button sendButton;

    private Larry larry;

    /**
     * Sets the Larry instance used by this GUI.
     *
     * @param larry Larry instance.
     */
    public void setLarry(Larry larry) {
        this.larry = larry;
        addLarryMessage("Hello! I'm Larry :)\nWhat can I do for you?");
    }

    @FXML
    private void handleUserInput() {
        String input = userInput.getText();

        if (input.isBlank()) {
            return;
        }

        addUserMessage(input);
        userInput.clear();

        String response = larry.getResponse(input);
        addLarryMessage(response);
    }

    /**
     * Adds a user message bubble to the conversation.
     *
     * @param message Message entered by the user.
     */
    private void addUserMessage(String message) {
        Label bubble = createBubble(
                message,
                "#202124",
                "white"
        );

        HBox row = new HBox(bubble);
        row.setAlignment(Pos.CENTER_RIGHT);
        row.setPadding(new Insets(3, 0, 3, 60));

        dialogContainer.getChildren().add(row);
        scrollToBottom();
    }

    /**
     * Adds a Larry response bubble to the conversation.
     *
     * @param message Response generated by Larry.
     */
    private void addLarryMessage(String message) {
        Label avatar = new Label("L");
        avatar.setAlignment(Pos.CENTER);
        avatar.setMinSize(32, 32);
        avatar.setMaxSize(32, 32);
        avatar.setStyle(
                "-fx-background-color: #202124;"
                        + "-fx-background-radius: 16;"
                        + "-fx-text-fill: white;"
                        + "-fx-font-weight: bold;"
        );

        Label bubble = createBubble(
                message,
                "#eeeeec",
                "#202124"
        );

        VBox messageBox = new VBox(4);

        Label name = new Label("Larry");
        name.setStyle(
                "-fx-text-fill: #777777;"
                        + "-fx-font-size: 10px;"
                        + "-fx-font-weight: bold;"
        );

        messageBox.getChildren().addAll(name, bubble);

        HBox row = new HBox(9, avatar, messageBox);
        row.setAlignment(Pos.TOP_LEFT);
        row.setPadding(new Insets(3, 60, 3, 0));

        dialogContainer.getChildren().add(row);
        scrollToBottom();
    }

    /**
     * Creates a styled chat bubble for a conversation message.
     *
     * @param message Text displayed in the bubble.
     * @param background Background colour of the bubble.
     * @param textColor Text colour of the bubble.
     * @return Label configured as a chat bubble.
     */
    private Label createBubble(String message, String background, String textColor) {
        Label bubble = new Label(message);

        bubble.setWrapText(true);
        bubble.setMaxWidth(300);
        bubble.setPadding(new Insets(10, 14, 10, 14));

        bubble.setStyle(
                "-fx-background-color: " + background + ";"
                        + "-fx-background-radius: 14;"
                        + "-fx-text-fill: " + textColor + ";"
                        + "-fx-font-size: 13px;"
        );

        return bubble;
    }

    /**
     * Scrolls the conversation view to the latest message.
     */
    private void scrollToBottom() {
        scrollPane.layout();
        scrollPane.setVvalue(1.0);
    }
}
