package floppy;

import java.io.IOException;
import java.util.Collections;

import javafx.collections.FXCollections;
import javafx.collections.ObservableList;
import javafx.fxml.FXML;
import javafx.fxml.FXMLLoader;
import javafx.geometry.Pos;
import javafx.scene.Node;
import javafx.scene.control.Label;
import javafx.scene.image.Image;
import javafx.scene.image.ImageView;
import javafx.scene.layout.HBox;

/**
 * Displays a chat message together with an image representing its speaker.
 */
public class DialogBox extends HBox {
    @FXML
    private Label dialog;

    @FXML
    private ImageView displayPicture;

    private DialogBox(String text, Image image) {
        try {
            FXMLLoader fxmlLoader = new FXMLLoader(
                    DialogBox.class.getResource("/view/DialogBox.fxml"));
            fxmlLoader.setController(this);
            fxmlLoader.setRoot(this);
            fxmlLoader.load();
        } catch (IOException exception) {
            throw new AssertionError("Unable to load the dialog-box layout.", exception);
        }

        dialog.setText(text);
        displayPicture.setImage(image);
    }

    /**
     * Creates a dialog aligned for a message from the user.
     *
     * @param text Message entered by the user.
     * @param image Image representing the user.
     * @return Dialog containing the user's message.
     */
    public static DialogBox getUserDialog(String text, Image image) {
        DialogBox dialogBox = new DialogBox(text, image);
        dialogBox.getStyleClass().add("user-dialog");
        return dialogBox;
    }

    /**
     * Creates a flipped dialog aligned for a response from Floppy.
     *
     * @param text Response generated by Floppy.
     * @param image Image representing Floppy.
     * @return Dialog containing Floppy's response.
     */
    public static DialogBox getFloppyDialog(String text, Image image) {
        DialogBox dialogBox = new DialogBox(text, image);
        dialogBox.getStyleClass().add("floppy-dialog");
        dialogBox.flip();
        return dialogBox;
    }

    /**
     * Creates a highlighted dialog for an error reported by Floppy.
     *
     * @param text Error message generated by Floppy.
     * @param image Image representing Floppy.
     * @return Dialog containing the highlighted error message.
     */
    public static DialogBox getErrorDialog(String text, Image image) {
        DialogBox dialogBox = new DialogBox(text, image);
        dialogBox.getStyleClass().add("error-dialog");
        dialogBox.flip();
        return dialogBox;
    }

    /**
     * Places the speaker image on the left and aligns the dialog accordingly.
     */
    private void flip() {
        ObservableList<Node> children = FXCollections.observableArrayList(getChildren());
        Collections.reverse(children);
        getChildren().setAll(children);
        setAlignment(Pos.TOP_LEFT);
    }
}
