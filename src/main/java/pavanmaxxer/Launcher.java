package pavanmaxxer;

/**
 * Starts the JavaFX application without extending a JavaFX class.
 */
public final class Launcher {
    private Launcher() {
    }

    /**
     * Launches the Pavanmaxxer GUI.
     *
     * @param args Command-line arguments passed to JavaFX.
     */
    public static void main(String[] args) {
        Main.main(args);
    }
}
