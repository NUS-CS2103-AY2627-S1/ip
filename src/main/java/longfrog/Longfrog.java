package longfrog;

import java.util.ArrayList;
import java.util.List;

import longfrog.command.Command;
import longfrog.exception.LongfrogException;
import longfrog.parser.Parser;
import longfrog.storage.Storage;
import longfrog.task.TaskList;
import longfrog.ui.Ui;

/** Coordinates command parsing, task persistence, and the console UI. */
public class Longfrog {
    private static final String FILE_PATH = "data/longfrog.txt";
    private final Storage storage;
    private final TaskList taskList;
    private final Ui ui;
    private final List<String> responseMessages;
    private final Ui responseUi;
    private final Parser parser;
    private final String startupWarning;
    private boolean isExitRequested;

    /** Creates Longfrog using the supplied task storage file. */
    public Longfrog(String filePath) {
        ui = new Ui();
        responseMessages = new ArrayList<>();
        responseUi = new Ui(responseMessages::add);
        storage = new Storage(filePath);
        TaskList loadedTasks;
        try {
            loadedTasks = new TaskList(storage.load());
        } catch (LongfrogException e) {
            ui.showLoadingError();
            loadedTasks = new TaskList();
        }
        taskList = loadedTasks;
        parser = new Parser(taskList);
        startupWarning = createDuplicateWarning(taskList.countDuplicateEntries());
    }

    /** Starts the command loop and continues until the user enters {@code bye}. */
    public void run() {
        if (!startupWarning.isEmpty()) {
            ui.showMessage(startupWarning);
        }

        boolean isExit = false;
        while (!isExit) {
            String userInput = ui.readCommand();

            ui.showLine();
            isExit = executeCommand(userInput, ui);

            ui.showEmptyLine();
            ui.showLine();
            ui.showEmptyLine();
        }

        ui.close();
    }

    /**
     * Processes a GUI message and returns Longfrog's response as displayable text.
     *
     * @param input the raw command entered by the user
     * @return the response generated by Longfrog
     */
    public String getResponse(String input) {
        responseMessages.clear();
        isExitRequested = executeCommand(input, responseUi);
        return String.join(System.lineSeparator(), responseMessages);
    }

    /**
     * Returns whether the most recent GUI command requested application exit.
     *
     * @return whether the most recent command was {@code bye}
     */
    public boolean isExitRequested() {
        return isExitRequested;
    }

    /**
     * Returns the warning that should be displayed once when the user interface starts.
     *
     * @return the duplicate warning, or an empty string when the loaded data has no duplicates
     */
    public String getStartupWarning() {
        return startupWarning;
    }

    /**
     * Executes a parsed command and persists any resulting task-list changes.
     *
     * @param input the raw command to execute
     * @param outputUi the UI that receives the command response
     * @return whether the command requested application exit
     */
    private boolean executeCommand(String input, Ui outputUi) {
        assert input != null : "Command input must be supplied by the UI";
        assert outputUi != null : "Command output UI must be available during execution";

        try {
            Command command = parser.parse(input);
            assert command != null : "Parser must return a command for valid input";

            boolean isExit = command.execute(outputUi);
            if (!storage.save(taskList.getTasks())) {
                outputUi.showSavingError();
            }
            return isExit;
        } catch (LongfrogException e) {
            outputUi.showMessage(e.getMessage());
            return false;
        }
    }

    /**
     * Creates a grammatically correct warning for duplicate entries loaded from storage.
     *
     * @param duplicateCount the number of occurrences beyond each first occurrence
     * @return the warning, or an empty string when there are no duplicate entries
     */
    private String createDuplicateWarning(int duplicateCount) {
        if (duplicateCount == 0) {
            return "";
        }

        String entryLabel = duplicateCount == 1 ? "entry" : "entries";
        return "Warning: " + duplicateCount + " duplicate task " + entryLabel
                + " detected in saved data. Existing entries were preserved.";
    }

    /**
     * Starts Longfrog using its default save-file location.
     *
     * @param args command-line arguments, which are ignored
     */
    public static void main(String[] args) {
        new Longfrog(FILE_PATH).run();
    }
}
