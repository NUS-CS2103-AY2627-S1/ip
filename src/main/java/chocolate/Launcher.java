package chocolate;

import chocolate.gui.Main;

/**
 * Starts the JavaFX application without directly extending {@code Application}.
 */
public class Launcher {
    /**
     * Launches Chocolate's JavaFX user interface.
     *
     * @param args Command-line arguments passed to JavaFX.
     */
    public static void main(String[] args) {
        Main.main(args);
    }
}
